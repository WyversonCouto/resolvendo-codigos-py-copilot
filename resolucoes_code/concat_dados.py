# Vamos receber dois dados diferentes do usuário e concatena-los em uma única string?
# Solicita ao usuário o primeiro dado e armazena o texto informado.
dado1 = input("Digite o primeiro dado: ")
# Solicita ao usuário o segundo dado e armazena o texto informado.
dado2 = input("Digite o segundo dado: ")
# Junta os dois dados, separando-os por um espaço.
resultado = dado1 + " " + dado2
# Exibe a string resultante da concatenação.
print("A string concatenada é:", resultado)
