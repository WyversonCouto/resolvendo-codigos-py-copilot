# Vamos calcular a média de dois números fornecidos pelo usuário?
# Solicita ao usuário o primeiro número e converte a entrada para número decimal.
numero1 = float(input("Digite o primeiro número: "))

# Solicita ao usuário o segundo número e converte a entrada para número decimal.
numero2 = float(input("Digite o segundo número: "))

# Calcula a média dos dois números.
media = (numero1 + numero2) / 2

# Exibe a média calculada.
print("A média dos números é:", media)
